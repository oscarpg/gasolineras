#!/usr/bin/env python3
"""
Builds core/src/main/resources/es/gasolineras/core/provinces.txt from es-atlas' provinces.json.

Source: es-atlas (MIT, https://github.com/martgnz/es-atlas), built from the Instituto Geográfico
Nacional's reference data (CC BY 4.0, © Instituto Geográfico Nacional de España).

Usage:
  curl -sSLo es-atlas.tgz https://registry.npmjs.org/es-atlas/-/es-atlas-0.6.0.tgz && tar xzf es-atlas.tgz
  python3 -I android/scripts/build_province_shapes.py package/es/provinces.json android/core/src/main/resources/es/gasolineras/core/provinces.txt

Output: one line per province, `code|ring|ring...`, each ring `lon,lat;lon,lat;...` (WGS84, 4 decimals).
"""
import json
import sys


def main(src, dst):
    topo = json.load(open(src, encoding="utf-8"))
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]

    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        points = []
        for dx, dy in arc:
            x += dx
            y += dy
            points.append((x * sx + tx, y * sy + ty))
        arcs.append(points)

    def ring(indexes):
        out = []
        for i in indexes:
            points = arcs[i] if i >= 0 else list(reversed(arcs[~i]))
            out.extend(points if not out else points[1:])
        return out

    lines = []
    for g in topo["objects"]["provinces"]["geometries"]:
        code = str(g["id"]).zfill(2)
        if not 1 <= int(code) <= 52:
            continue  # not a province MITECO publishes (e.g. territories without one)
        polygons = g["arcs"] if g["type"] == "MultiPolygon" else [g["arcs"]]
        rings = [ring(r) for polygon in polygons for r in polygon]
        encoded = ["; ".join(f"{lon:.4f},{lat:.4f}" for lon, lat in r).replace(" ", "") for r in rings]
        lines.append(code + "|" + "|".join(encoded))
    lines.sort()
    with open(dst, "w", encoding="utf-8") as f:
        f.write("# Province outlines: es-atlas (MIT) from IGN data, CC BY 4.0 (c) Instituto Geografico Nacional de Espana.\n")
        f.write("# Generated by android/scripts/build_province_shapes.py. Format: code|lon,lat;...|ring...\n")
        f.write("\n".join(lines) + "\n")
    print(len(lines), "provinces,", sum(l.count(";") + l.count("|") for l in lines), "points")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
